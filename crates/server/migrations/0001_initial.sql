CREATE TABLE users(id TEXT PRIMARY KEY,username TEXT UNIQUE NOT NULL,password TEXT NOT NULL);
CREATE TABLE sessions(id TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),expires INTEGER NOT NULL);
CREATE TABLE libraries(id TEXT PRIMARY KEY,name TEXT NOT NULL,path TEXT UNIQUE NOT NULL,kind TEXT NOT NULL);
CREATE TABLE items(id TEXT PRIMARY KEY,library_id TEXT NOT NULL,path TEXT UNIQUE NOT NULL,data TEXT NOT NULL);
CREATE TABLE progress(user_id TEXT NOT NULL,item_id TEXT NOT NULL,position REAL NOT NULL,completed BOOLEAN NOT NULL,PRIMARY KEY(user_id,item_id));
